#include <iostream> // Include input-output stream library for console printing
#include <fstream>  // Include file stream library for reading puzzle text files
#include <vector>   // Include vector library to store the 9x9 grid and list of solutions
#include <string>   // Include string library for handling file names and strings

class SudokuSolver
{                                        // Define a class to represent and solve the Sudoku puzzle
private:                                 // Private section to encapsulate board data and helper methods
    std::vector<std::vector<int>> board; // 2D vector representing the 9x9 Sudoku board

    bool isValid(int row, int col, int num)
    { // Helper method to check if a number can be placed at a specific cell
        for (int i = 0; i < 9; ++i)
        { // Loop through each column in the current row
            if (board[row][i] == num)
                return false; // Return false if the number already exists in the row
        }
        for (int i = 0; i < 9; ++i)
        { // Loop through each row in the current column
            if (board[i][col] == num)
                return false; // Return false if the number already exists in the column
        }
        int startRow = row - row % 3; // Calculate the starting row index of the 3x3 subgrid
        int startCol = col - col % 3; // Calculate the starting column index of the 3x3 subgrid
        for (int r = 0; r < 3; ++r)
        { // Loop through the 3 rows of the subgrid
            for (int c = 0; c < 3; ++c)
            { // Loop through the 3 columns of the subgrid
                if (board[startRow + r][startCol + c] == num)
                    return false; // Return false if found in subgrid
            }
        }
        return true; // Return true if the placement is valid across row, col, and subgrid
    }

    // Function authored by Andy Garcia to detect if a digit is repeated on a row or column. Error detected by Claude and given assistance with logic and code implemented by Andy Garcia
    bool givensAreValid()
    {                               // new function to test if duplicate nums exist on the same row or col
        for (int r = 0; r < 9; ++r) // loop through every row
            for (int c = 0; c < 9; ++c)
            {                        // loop through every col
                int d = board[r][c]; // set d equal to the digit at the board spot looked at
                if (d == 0)
                    continue;               // skip blanks
                board[r][c] = 0;            // take it off the board
                bool ok = isValid(r, c, d); // does it conflict with the rest?
                board[r][c] = d;            // put it back
                if (!ok)
                    return false; // two givens clash
            }
        return true; // otherwise return true
    }

    int solutionCount = 0; // new private member added to count the number of solutions done

    // Code Change #3 : edited Gemini's code to stop storing a solution each time it was finished and instead print it off then clear it. Storage fix discovered by Claude and code implemented by Andy Garcia
    void solveRec(int row, int col)
    { // Recursive backtracking method. Removed solutions parameter (Andy Garcia)
        if (row == 9)
        {                                                       // Check if we have successfully processed past the last row
            ++solutionCount;                                    // count it
            std::cout << "Solution " << solutionCount << ":\n"; // prints what number solution it is on currently
            printBoard();                                       // print it now, then discard
            std::cout << "\n";                                  // prints new line
            return;                                             // ends the function
        }
        int nextRow = (col == 8) ? row + 1 : row; // Determine the row index for the next recursive step
        int nextCol = (col == 8) ? 0 : col + 1;   // Determine the column index for the next recursive step

        if (board[row][col] != 0)
        {                               // Check if the current cell is already filled from the initial puzzle
            solveRec(nextRow, nextCol); // Recurse to the next cell without changing current cell
        }
        else
        { // If the current cell is blank (represented by 0)
            for (int num = 1; num <= 9; ++num)
            { // Try digits 1 through 9 sequentially
                if (isValid(row, col, num))
                {                               // Check if placing the current digit is valid
                    board[row][col] = num;      // Place the number temporarily on the board
                    solveRec(nextRow, nextCol); // Recursively solve for the next cell
                    board[row][col] = 0;        // Backtrack by resetting the cell back to empty (0)
                }
            }
        }
    }

public: // Public interface for the SudokuSolver class
    SudokuSolver(const std::vector<std::vector<int>> &initialBoard)
    {                         // Constructor taking initial board
        board = initialBoard; // Initialize internal board with the provided puzzle
    }

    int findSolutions()
    { // Public method to trigger solving. Updated to take no parameters and return an int of how many solutions found (Andy Garcia)
        if (!givensAreValid())
            return 0;         // uses new method to quit and have no solution if a duplicate is detected (Andy Garcia)
        solveRec(0, 0);       // Start recursive backtracking from top-left cell (0,0)
        return solutionCount; // returns the solution count when findSolutions is called
    }

    void printBoard() const
    { // Method to print the current state of the board
        for (int r = 0; r < 9; ++r)
        { // Loop through each row of the board
            for (int c = 0; c < 9; ++c)
            { // Loop through each column of the row
                if (board[r][c] == 0)
                {                      // Check if the cell value is 0 (blank)
                    std::cout << "_ "; // Print an underscore for blank cells
                }
                else
                {                                    // If the cell contains a valid digit
                    std::cout << board[r][c] << " "; // Print the digit followed by a space
                }
            }
            std::cout << "\n"; // Print a newline at the end of each row
        }
    }
};

class PuzzleManager
{       // Class to manage reading files and running the solver
public: // Public methods for file management
    void processPuzzle(const std::string &filename)
    {
        std::ifstream infile(filename); // Open the file input stream

        std::cout << "File: " << filename << "\n"; // Print the current file name

        if (!infile.is_open())
        {                                                                     // Check if the file failed to open
            std::cout << "Error: Could not open file " << filename << "\n\n"; // Print error message
            return;                                                           // Skip to the next file iteration
        }

        std::vector<std::vector<int>> initialBoard(9, std::vector<int>(9, 0)); // Initialize 9x9 grid with zeros
        bool readSuccess = true;                                               // Flag to track successful file parsing
        for (int r = 0; r < 9; ++r)
        { // Loop through 9 rows of the puzzle file
            for (int c = 0; c < 9; ++c)
            {            // Loop through 9 columns per row
                char ch; // Variable to hold the character read from file
                if (!(infile >> ch))
                {                        // Attempt to read a character from the file stream
                    readSuccess = false; // Mark read failure if insufficient data exists
                    break;               // Break out of column loop
                }
                if (ch == '_')
                {                           // Check if character represents a blank cell
                    initialBoard[r][c] = 0; // Store 0 for blank cells internally
                }
                else if (ch >= '1' && ch <= '9')
                {                                  // Check if character is a digit 1 through 9
                    initialBoard[r][c] = ch - '0'; // Convert char digit to integer and store
                }
                else
                {                        // Handle unexpected characters in the file
                    readSuccess = false; // CODE CHANGE #1 : This detects a bad character and will indicate that to readSuccess (Idea presented by Claude, code written and commented by Andy Garcia)
                    break;               // leaves the column loop
                }
            }
            if (!readSuccess)
                break; // Break outer loop if reading failed
        }
        infile.close(); // Close the file stream safely

        if (!readSuccess)
        {                                                                   // Check if puzzle was formatted correctly
            std::cout << "Error: Invalid puzzle in " << filename << "\n\n"; //  will now print an error message when a file is not correct. (Andy Garcia)
            return;                                                         // returns to move on to next file after detecting bad one. (Andy Garcia)
        }

        SudokuSolver solver(initialBoard);        // one object for the whole puzzle

        std::cout << "Original Puzzle:\n";    // prints line before original puzzle 
        solver.printBoard();                      // prints before solving to avoid using two solvers
        int count = solver.findSolutions(); // solutions print as they're found
        if (count == 0)
        {                                         // check if there were no solutions found   (Andy Garcia)
            std::cout << "No solution found\n\n"; // print no solutions found  (Andy Garcia)
        }
        else
        {
            std::cout << "Solutions found: " << count << "\n\n"; //   print how many solutions were found  (Andy Garcia)
        }
    }

    void run()
    { // Main execution method to process all 5 puzzle files
        for (int fileIndex = 1; fileIndex <= 5; ++fileIndex)
        {                                                                         // Loop from 1 to 5 for puzzle files
            std::string filename = "puzzle" + std::to_string(fileIndex) + ".txt"; // Construct file name string
            processPuzzle(filename);                                              // call new function to shrink run and improve maintainability (Andy Garcia)
        }
    }
};

int main()
{                          // Main entry point of the C++ program
    PuzzleManager manager; // Create an instance of the PuzzleManager class
    manager.run();         // Invoke the run method to process all puzzle files
    return 0;              // Return 0 to indicate successful program termination
}